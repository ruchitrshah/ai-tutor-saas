import React, {
  forwardRef,
  useCallback,
  useEffect,
  useImperativeHandle,
  useRef,
  useState,
} from 'react';
import { Animated, Modal, Platform, StyleSheet, View } from 'react-native';
import LottieView from './LottieSurface';
import * as Haptics from 'expo-haptics';

import { Colors, Space, Type, Motion } from '../brand';
import { useReducedMotion } from '../brand/Motion';

/**
 * The full-page beat between one Discover profile and the next.
 *
 * Connect and Skip both hand the screen over to this for about a second: a
 * Lottie animation, a line saying what just happened, and a short run of
 * haptics timed against the animation's own frames. The next profile is swapped
 * in underneath while the page is fully covered, then this fades away to reveal
 * it — so there is no moment where one profile visibly turns into another.
 *
 * Connect is the rare, committed action and gets the long, lively version.
 * Skip is the frequent one, so it is shorter and quieter. If both performed
 * equally the app would be performing all day.
 *
 * It is a transparent Modal rather than a View inside Discover because the tab
 * bar floats above the screen's content; only a Modal covers it, and a "full
 * page" moment with a tab bar poking through is not full page.
 *
 * ── Timeline (ms) ──────────────────────────────────────────────────────────
 * The numbers are tied to frames in assets/animations/*.json (60fps), which are
 * generated by tools/lottie/generate.py. Move a keyframe there and the matching
 * haptic here has to move with it:
 *
 *   connect   f14 = 233ms  heart pops + burst begins   → heavy, then rigid, light, light
 *             f44 = 733ms  tick finishes drawing        → success notification
 */

export const MOMENT_CONNECT = 'connect';
export const MOMENT_SKIP = 'skip';

const connectSource = require('../../assets/animations/connect-burst.json');
const skipSource = require('../../assets/animations/skip-swoosh.json');

const FADE_IN_MS = 160;
const FADE_OUT_MS = 240;

const TIMELINES = {
  [MOMENT_CONNECT]: {
    source: connectSource,
    size: 340,
    advanceAt: 450,   // fully covered by 160ms; heart has popped by 233ms
    textAt: 300,
    subAt: 460,
    outAt: 1320,      // animation is 1.4s; leave while it is still pulsing
    haptics: [
      [230, 'heavy'],
      [300, 'rigid'],
      [360, 'light'],
      [420, 'light'],
      [733, 'success'],
    ],
  },
  [MOMENT_SKIP]: {
    source: skipSource,
    size: 300,
    advanceAt: 230,
    textAt: 80,
    subAt: 160,
    outAt: 640,
    haptics: [
      [0, 'light'],
      [140, 'tick'],
      [230, 'tick'],
      [320, 'tick'],
    ],
  },
};

function fireHaptic(kind) {
  if (Platform.OS === 'web') return;
  const run = {
    heavy: () => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Heavy),
    rigid: () => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Rigid),
    light: () => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light),
    tick: () => Haptics.selectionAsync(),
    success: () => Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success),
  }[kind];
  try {
    run?.()?.catch?.(() => {});
  } catch (_) {
    // Haptics are a nicety — never let one break the flow.
  }
}

const DecisionMoment = forwardRef(function DecisionMoment(_props, ref) {
  const reduced = useReducedMotion();

  const [visible, setVisible] = useState(false);
  const [view, setView] = useState({ kind: MOMENT_SKIP, title: '', sub: '', run: 0 });

  const bg = useRef(new Animated.Value(0)).current;
  const title = useRef(new Animated.Value(0)).current;
  const sub = useRef(new Animated.Value(0)).current;

  const timers = useRef([]);
  const activeRef = useRef(false);

  const later = useCallback((ms, fn) => {
    timers.current.push(setTimeout(fn, ms));
  }, []);

  useEffect(
    () => () => {
      timers.current.forEach(clearTimeout);
      timers.current = [];
    },
    []
  );

  const play = useCallback(
    (kind, { title: titleText, sub: subText, onCovered, onDone } = {}) => {
      // One at a time. The caller also gates on this, so a second tap during a
      // moment is dropped rather than queued — queued, it would skip two
      // profiles for one decision.
      if (activeRef.current) return false;
      activeRef.current = true;

      const tl = TIMELINES[kind];
      bg.setValue(0);
      title.setValue(0);
      sub.setValue(0);
      setView((v) => ({ kind, title: titleText, sub: subText, run: v.run + 1 }));
      setVisible(true);

      Animated.timing(bg, {
        toValue: 1,
        duration: FADE_IN_MS,
        easing: Motion.ease.out,
        useNativeDriver: true,
      }).start();

      later(tl.textAt, () =>
        Animated.timing(title, {
          toValue: 1,
          duration: 260,
          easing: Motion.ease.out,
          useNativeDriver: true,
        }).start()
      );
      later(tl.subAt, () =>
        Animated.timing(sub, {
          toValue: 1,
          duration: 260,
          easing: Motion.ease.out,
          useNativeDriver: true,
        }).start()
      );

      tl.haptics.forEach(([ms, type]) => later(ms, () => fireHaptic(type)));

      // Swap the profile while nothing of it is visible.
      later(tl.advanceAt, () => onCovered?.());

      later(tl.outAt, () => {
        // Slightly slower out than in: this is the reveal of the next profile.
        Animated.timing(bg, {
          toValue: 0,
          duration: FADE_OUT_MS,
          easing: Motion.ease.out,
          useNativeDriver: true,
        }).start(() => {
          setVisible(false);
          activeRef.current = false;
          onDone?.();
        });
      });

      return true;
    },
    [bg, title, sub, later]
  );

  useImperativeHandle(ref, () => ({ play }), [play]);

  const connect = view.kind === MOMENT_CONNECT;
  const tl = TIMELINES[view.kind];

  const titleStyle = {
    opacity: title,
    transform: [
      {
        translateY: title.interpolate({ inputRange: [0, 1], outputRange: [reduced ? 0 : 14, 0] }),
      },
    ],
  };
  const subStyle = {
    opacity: sub,
    transform: [
      {
        translateY: sub.interpolate({ inputRange: [0, 1], outputRange: [reduced ? 0 : 10, 0] }),
      },
    ],
  };

  return (
    <Modal
      visible={visible}
      transparent
      animationType="none"
      statusBarTranslucent
      hardwareAccelerated
      onRequestClose={() => {}}
    >
      <Animated.View
        style={[
          StyleSheet.absoluteFill,
          connect ? styles.connectBg : styles.skipBg,
          { opacity: bg },
        ]}
      />

      <View style={styles.content} pointerEvents="none">
        <Animated.View style={{ opacity: bg }}>
          <LottieView
            // New key per play so the animation always starts from frame 0.
            key={view.run}
            source={tl.source}
            autoPlay={!reduced}
            progress={reduced ? 0.6 : undefined}
            loop={false}
            resizeMode="contain"
            style={{ width: tl.size, height: tl.size }}
          />
        </Animated.View>

        <Animated.Text style={[styles.title, connect ? styles.onDark : styles.onLight, titleStyle]}>
          {view.title}
        </Animated.Text>
        {!!view.sub && (
          <Animated.Text style={[styles.sub, connect ? styles.subOnDark : styles.subOnLight, subStyle]}>
            {view.sub}
          </Animated.Text>
        )}
      </View>
    </Modal>
  );
});

export default DecisionMoment;

const styles = StyleSheet.create({
  connectBg: { backgroundColor: Colors.brand.primary },
  skipBg: { backgroundColor: Colors.surface.page },
  content: {
    flex: 1,
    alignItems: 'center',
    justifyContent: 'center',
    paddingHorizontal: Space[24],
  },
  title: {
    ...Type.pageTitle,
    textAlign: 'center',
    marginTop: Space[8],
  },
  sub: {
    ...Type.subtitle,
    textAlign: 'center',
    marginTop: Space[8],
  },
  onDark: { color: '#fff' },
  onLight: { color: Colors.brand.primary },
  subOnDark: { color: 'rgba(255,255,255,0.72)' },
  subOnLight: { color: Colors.text.secondary },
});
